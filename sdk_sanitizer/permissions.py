PREFIX = "android.permission."


def normalize(name):
    """Привести имя разрешения к короткой форме (без android.permission.)."""
    name = (name or "").strip()
    if name.startswith(PREFIX):
        return name[len(PREFIX):]
    return name


def assess_permissions(permissions):
    """permissions — список имён разрешений из манифеста/APK.

    Возвращает список словарей по опасным разрешениям, отсортированный по
    убыванию серьёзности:
        {"permission", "name", "severity", "note"}
    Дубликаты схлопываются, неизвестные/нечувствительные разрешения пропускаются.
    """
    seen = set()
    out = []
    for raw in permissions or []:
        short = normalize(raw)
        if short in seen or short not in DANGEROUS_PERMISSIONS:
            continue
        seen.add(short)
        sev, note = DANGEROUS_PERMISSIONS[short]
        out.append({
            "permission": raw,
            "name": short,
            "severity": sev,
            "note": note,
        })
    out.sort(key=lambda r: (-SEV_ORDER[r["severity"]], r["name"]))
    return out


def max_permission_severity(assessed):
    """Максимальная серьёзность среди опасных разрешений ('none', если нет)."""
    order = {"none": 0, **SEV_ORDER}
    m = "none"
    for r in assessed:
        if order.get(r["severity"], 0) > order[m]:
            m = r["severity"]
    return m
